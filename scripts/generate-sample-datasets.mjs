/**
 * Writes the dataset table on pages/querying/sample-datasets.mdx from the public
 * dataset catalog that Memgraph Lab also reads.
 *
 * Usage:
 *   node scripts/generate-sample-datasets.mjs              fetch the catalog
 *   node scripts/generate-sample-datasets.mjs --from FILE  read a saved copy
 *
 * Replaces everything between the start and end markers on the page. The
 * "Update sample datasets" workflow runs it daily and opens a PR when the table
 * changed. It isn't part of the build, so a build never depends on
 * download.memgraph.com.
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const PAGE = path.join(ROOT, 'pages/querying/sample-datasets.mdx')
const CATALOG = 'https://download.memgraph.com/datasets/items.v1.json'
const USER_AGENT = 'Mozilla/5.0 (compatible; memgraph-docs-checks)'
const START = '{/* sample-datasets:start, generated by scripts/generate-sample-datasets.mjs */}'
const END = '{/* sample-datasets:end */}'
const MAX_DESC = 150

// Datasets that have a tutorial under Exploring datasets.
const TUTORIALS = {
  'ted-talks': 'analyzing-ted-talks',
  'europe-backpacking': 'backpacking-through-europe',
  'europe-road-network': 'exploring-the-european-road-network',
  'football-player-transfers': 'football-transfers',
  'game-of-thrones-deaths': 'got-deaths',
  'football-premier-league-games': 'graphing-the-premier-league',
  'marvel-cinematic-universe': 'marvel-universe',
  movielens: 'movie-recommendation',
}

async function loadCatalog() {
  const i = process.argv.indexOf('--from')
  if (i !== -1) return JSON.parse(fs.readFileSync(process.argv[i + 1], 'utf8'))
  const response = await fetch(CATALOG, { headers: { 'User-Agent': USER_AGENT } })
  if (!response.ok) throw new Error(`${CATALOG}: HTTP ${response.status}`)
  return response.json()
}

function firstSentence(text) {
  const clean = text.replace(/\s+/g, ' ').trim()
  const sentence = clean.match(/^.+?[.!?](?=\s|$)/)?.[0] ?? clean
  const short = sentence.length > MAX_DESC ? `${sentence.slice(0, MAX_DESC - 1).replace(/\s+\S*$/, '')}…` : sentence
  return /[.!?…]$/.test(short) ? short : `${short}.`
}

function cell(text) {
  return text.replace(/\|/g, '\\|').replace(/</g, '&lt;').replace(/{/g, '&#123;').replace(/}/g, '&#125;')
}

function row(dataset) {
  const tutorial = TUTORIALS[dataset.slug]
  const description = cell(firstSentence(dataset.description)) +
    (tutorial ? ` See the [tutorial](/querying/exploring-datasets/${tutorial}).` : '')
  const nodes = dataset.counts.nodes.toLocaleString('en-US')
  const relationships = dataset.counts.relationships.toLocaleString('en-US')
  const file = dataset.formats?.cypherl?.url
  return `| ${cell(dataset.title)} | \`${dataset.slug}\` | ${description} | ${nodes} | ${relationships} | ${file ? `[CYPHERL](${file})` : '-'} |`
}

const catalog = await loadCatalog()
const datasets = [...catalog.datasets].sort((a, b) => a.title.localeCompare(b.title, 'en'))
const table = [
  '| Dataset | Slug | Description | Nodes | Relationships | File |',
  '| --- | --- | --- | --- | --- | --- |',
  ...datasets.map(row),
].join('\n')

const page = fs.readFileSync(PAGE, 'utf8')
const start = page.indexOf(START)
const end = page.indexOf(END)
if (start === -1 || end === -1 || end < start) throw new Error(`Markers not found in ${PAGE}`)
const updated = `${page.slice(0, start + START.length)}\n\n${table}\n\n${page.slice(end)}`
fs.writeFileSync(PAGE, updated)
console.log(`Wrote ${datasets.length} datasets to ${path.relative(ROOT, PAGE)}`)
